from collections.abc import AsyncIterator

from maritime.core.exceptions import InvariantViolationError
from maritime.core.telemetry.logging import get_logger
from maritime.core.telemetry.tracer import span
from maritime.modules.indexing.domain.ports import IEmbeddingService
from maritime.modules.rag.domain.ports import ILlmService, IQueryEngine
from maritime.modules.rag.domain.services import StrictCitationValidator
from maritime.modules.rag.domain.value_objects import (
    Citation,
    RagResponse,
    RetrievedChunk,
    StreamChunk,
    StreamDeltaChunk,
    StreamMetaChunk,
)

logger = get_logger(__name__)

INSUFFICIENT_EVIDENCE_ANSWER = (
    "No hay evidencia suficiente en los contratos disponibles para responder a esta pregunta."
)


class AskContractQuestionUseCase:
    """Use case to orchestrate semantic retrieval, LLM response synthesis, and strict citation validation."""

    def __init__(
        self,
        query_engine: IQueryEngine,
        llm_service: ILlmService,
        embedding_service: IEmbeddingService,
        citation_validator: StrictCitationValidator,
        similarity_threshold: float = 0.25,
    ) -> None:
        self._query_engine = query_engine
        self._llm_service = llm_service
        self._embedding_service = embedding_service
        self._citation_validator = citation_validator
        self._similarity_threshold = similarity_threshold

    async def execute(
        self,
        query: str,
        top_k: int = 5,
        document_id: str | None = None,
    ) -> RagResponse:
        cleaned_query = query.strip()
        if not cleaned_query:
            raise InvariantViolationError("Query cannot be empty.")

        logger.info(
            "Executing contract question query",
            extra={"query_length": len(cleaned_query), "top_k": top_k, "document_id": document_id},
        )

        valid_chunks = await self._retrieve_context(cleaned_query, top_k, document_id)

        # Synthesize natural answer with LLM using retrieved context (or empty list if no chunks meet threshold)
        llm_response = await self._llm_service.generate_answer(
            query=cleaned_query,
            context_chunks=valid_chunks,
        )

        validated_citations = self._validate_citations(llm_response.citations, valid_chunks)

        # If LLM provided citations but none matched valid chunks, reject them
        if len(llm_response.citations) > 0 and len(validated_citations) == 0:
            logger.warning(
                "All citations generated by LLM were rejected by StrictCitationValidator"
            )
            return RagResponse(
                answer=llm_response.answer,
                citations=[],
                has_sufficient_evidence=False,
                confidence_score=0.0,
            )

        confidence_score: float | None = valid_chunks[0].similarity_score if valid_chunks else None

        return RagResponse(
            answer=llm_response.answer,
            citations=validated_citations,
            has_sufficient_evidence=llm_response.has_sufficient_evidence,
            confidence_score=confidence_score,
        )

    async def execute_stream(
        self,
        query: str,
        top_k: int = 5,
        document_id: str | None = None,
    ) -> AsyncIterator[StreamChunk]:
        cleaned_query = query.strip()
        if not cleaned_query:
            raise InvariantViolationError("Query cannot be empty.")

        logger.info(
            "Executing streaming contract question query",
            extra={"query_length": len(cleaned_query), "top_k": top_k, "document_id": document_id},
        )

        valid_chunks = await self._retrieve_context(cleaned_query, top_k, document_id)

        # Stream answer from LLM service
        async for chunk in self._llm_service.generate_answer_stream(
            query=cleaned_query,
            context_chunks=valid_chunks,
        ):
            if isinstance(chunk, StreamDeltaChunk):
                yield chunk
            elif isinstance(chunk, StreamMetaChunk):
                validated_citations = self._validate_citations(chunk.citations, valid_chunks)

                # If citations were provided but none matched valid chunks, reject
                if len(chunk.citations) > 0 and len(validated_citations) == 0:
                    logger.warning(
                        "All citations generated by LLM stream were rejected by StrictCitationValidator"
                    )
                    yield StreamMetaChunk(
                        citations=[],
                        has_sufficient_evidence=False,
                        confidence_score=0.0,
                    )
                else:
                    confidence_score: float | None = (
                        valid_chunks[0].similarity_score if valid_chunks else chunk.confidence_score
                    )
                    yield StreamMetaChunk(
                        citations=validated_citations,
                        has_sufficient_evidence=chunk.has_sufficient_evidence,
                        confidence_score=confidence_score,
                    )

    async def _retrieve_context(
        self, cleaned_query: str, top_k: int, document_id: str | None
    ) -> list[RetrievedChunk]:
        """Embeds the question, retrieves candidates and keeps those above the similarity threshold."""
        with span("rag.embed_query", **{"rag.query_length": len(cleaned_query)}):
            query_vector = self._embedding_service.embed_text(cleaned_query)

        with span("rag.retrieve", **{"rag.top_k": top_k}) as retrieve_span:
            chunks = await self._query_engine.retrieve_chunks(
                query_vector=query_vector,
                top_k=top_k,
                document_id=document_id,
            )
            valid_chunks = [
                chunk for chunk in chunks if chunk.similarity_score >= self._similarity_threshold
            ]
            # Why an answer abstains is visible here: nothing retrieved, or nothing close enough.
            retrieve_span.set_attribute("rag.retrieved_chunks", len(chunks))
            retrieve_span.set_attribute("rag.threshold", self._similarity_threshold)
            retrieve_span.set_attribute("rag.chunks_above_threshold", len(valid_chunks))
            retrieve_span.set_attribute("rag.context_empty", not valid_chunks)
            if chunks:
                retrieve_span.set_attribute(
                    "rag.top_similarity", max(chunk.similarity_score for chunk in chunks)
                )
        return valid_chunks

    def _validate_citations(
        self, citations: list[Citation], valid_chunks: list[RetrievedChunk]
    ) -> list[Citation]:
        """Keeps only the citations that really exist in the retrieved context."""
        with span(
            "rag.validate_citations",
            **{
                "rag.citations.proposed": len(citations),
                "rag.chunks_in_context": len(valid_chunks),
            },
        ) as validation_span:
            validated: list[Citation] = []
            if citations and valid_chunks:
                validated = self._citation_validator.validate(
                    citations=citations,
                    context_chunks=valid_chunks,
                )
            validation_span.set_attribute("rag.citations.accepted", len(validated))
            validation_span.set_attribute("rag.citations.rejected", len(citations) - len(validated))
        return validated
